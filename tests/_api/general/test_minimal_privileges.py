import pytest

from pgmig import agenerate
from tests._api.generate_setup import GenerateSetup
from tests._api.ownership import ensure_role

# A schema nobody but its owner may use, holding one object of every kind pgmig introspects.
# Mixed-case and special-character names exercise the identifier quoting of every name the
# introspection has to print itself.
_LOCKED_SCHEMA_SQL = [
    "CREATE SCHEMA locked",
    "CREATE TYPE locked.mood AS ENUM ('happy', 'sad')",
    "CREATE DOMAIN locked.positive AS integer CHECK (VALUE > 0)",
    "CREATE TYPE locked.pair AS (a integer, b locked.mood)",
    "CREATE TYPE locked.float_range AS RANGE (subtype = float8)",
    "CREATE SEQUENCE locked.standalone_seq",
    "CREATE FUNCTION locked.touch() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END'",
    "CREATE FUNCTION locked.one() RETURNS integer LANGUAGE sql AS 'SELECT 1'",
    """CREATE TABLE locked.person (
        id serial PRIMARY KEY,
        big_id bigserial,
        ident integer GENERATED ALWAYS AS IDENTITY,
        mood locked.mood,
        amount locked.positive,
        pair locked.pair,
        span locked.float_range,
        counter integer DEFAULT nextval('locked.standalone_seq'),
        computed integer DEFAULT locked.one(),
        name text UNIQUE CHECK (name <> '')
    )""",
    'CREATE TABLE locked."Mixed Case" ("My Id" serial, "Ident-ity" integer GENERATED BY DEFAULT AS IDENTITY)',
    'CREATE TABLE locked."we""ird.tbl" ("we""ird.col" serial)',
    "CREATE TABLE locked.child (person_id integer REFERENCES locked.person (id))",
    "CREATE INDEX person_mood_idx ON locked.person (mood)",
    "COMMENT ON TABLE locked.person IS 'people'",
    "COMMENT ON COLUMN locked.person.name IS 'full name'",
    "CREATE TRIGGER person_touch BEFORE UPDATE ON locked.person FOR EACH ROW EXECUTE FUNCTION locked.touch()",
    "ALTER TABLE locked.person ENABLE ROW LEVEL SECURITY",
    "CREATE POLICY person_policy ON locked.person USING (id > 0)",
    "CREATE VIEW locked.person_view AS SELECT id, name, mood FROM locked.person",
    "CREATE MATERIALIZED VIEW locked.person_matview AS SELECT id, name FROM locked.person",
    "CREATE INDEX person_matview_idx ON locked.person_matview (id)",
    "ALTER DEFAULT PRIVILEGES IN SCHEMA locked GRANT SELECT ON TABLES TO PUBLIC",
    "REVOKE ALL ON SCHEMA locked FROM PUBLIC",
]


@pytest.mark.parametrize("restricted_side", ["source", "target"])
@pytest.mark.parametrize("ignored", [True, False], ids=["ignored", "not_ignored"])
async def test_login_only_role_generates_like_the_owner(
    gen_setup: GenerateSetup, restricted_side: str, *, ignored: bool
) -> None:
    """
    A role with LOGIN only (no grants at all, read-only transactions) generates the same migration
    as the owner, whether or not the schema it has no USAGE on is ignored: the system catalogs are
    readable by every role, so introspection must not need privileges on the objects it describes.
    """
    role = await ensure_role(gen_setup, "pgmig_login_only")
    await gen_setup.src.execute(f"ALTER ROLE {role} LOGIN PASSWORD 'pgmig'")
    await gen_setup.src.execute(f"ALTER ROLE {role} SET default_transaction_read_only = on")

    # The objects live on the restricted side; the other database stays empty.
    restricted_conn = gen_setup.src if restricted_side == "source" else gen_setup.dst
    await restricted_conn.execute(";\n".join(_LOCKED_SCHEMA_SQL))

    owner_dsn = restricted_conn.dsn
    restricted_dsn = owner_dsn.replace("pgmig:pgmig@", f"{role}:pgmig@")
    assert restricted_dsn != owner_dsn

    async def generate(restricted_side_dsn: str) -> str:
        return await agenerate(
            source=restricted_side_dsn if restricted_side == "source" else gen_setup.src.dsn,
            target=restricted_side_dsn if restricted_side == "target" else gen_setup.dst.dsn,
            ignore_schemas=["locked"] if ignored else [],
            include_owner=True,
            include_grants=True,
            driver=gen_setup.driver,
        )

    as_owner = await generate(owner_dsn)
    as_restricted = await generate(restricted_dsn)

    assert as_restricted == as_owner

    # Guard against both runs agreeing on a wrong answer.
    if ignored:
        assert as_owner == ""
    elif restricted_side == "target":
        assert '"id" serial' in as_owner
        assert '"big_id" bigserial' in as_owner
        assert '"ident" integer GENERATED ALWAYS AS IDENTITY' in as_owner
        assert '"My Id" serial' in as_owner
        assert '"Ident-ity" integer GENERATED BY DEFAULT AS IDENTITY' in as_owner
        assert '"we""ird.col" serial' in as_owner
    else:
        assert 'DROP TABLE "locked"."person"' in as_owner
